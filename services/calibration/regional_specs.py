"""Regional calibration recipes (data/reference/calibration_protocol.json 'regional', crop-calib-reg-v1): the slots a
crop × region allows, generated by the pre-registered rule, and the regional coverage — each crop × region with its
recipe or the reason it has none.

A slot is a region that holds its country's declared regional yield series (data/reference/yield_series.json
'regional_sources') for the crop and whose border is known (services.reference.region_shapes). It gets a recipe when
the series has the protocol's years, the region holds the protocol's share of the crop's mapped area in its country and
a season is stated for it (services.calibration.seasons.region_season). The recipe reads that series (named source and
region), the weather over the crop's area inside the region, the protocol's one driver. As for national recipes, a
recipe no longer generated is retired with the reason unless it has a publication (left for a reviewer). Nothing is run
or published here; the regional coverage rows are replaced whole on each generation.
"""
from __future__ import annotations

from sqlalchemy import text
from sqlalchemy.orm import Session

from ml.features import yield_series
from ml.features.crop_registry import crops as registry
from ml.features.crop_registry import is_alternate_bearing
from services.calibration import crop_area, seasons, specs
from services.calibration import crop_area_weights as W
from services.calibration.gates import protocol
from services.calibration.registry_specs import ERA5_FIRST, _differs, _m49, retire
from services.reference import region_shapes


def rule() -> dict:
    return protocol()["regional"]


def min_share() -> float:
    return float(rule()["min_area_share"])


def min_years() -> int:
    return int(rule()["min_years_since_1991"])


def source_for(country: str) -> str | None:
    """The one regional yield series a country's regions read (None: the country has no regional recipes)."""
    rs = yield_series.rules()["regional_sources"]
    if country in rs:
        return rs[country]
    return rs.get("nuts2") if region_shapes.scheme_of(country) == "nuts2" else None


def held_regions(session: Session, commodity: str) -> dict[str, tuple[str, str]]:
    """{region: (country, source)} — the regions holding their country's declared regional series of the crop, with a
    known border."""
    borders = region_shapes.shapes()
    out = {}
    for country, region, source in yield_series.regional_series(session, commodity):
        if region in borders and source == source_for(country) and region_shapes.country_of(region) == country:
            out[region] = (country, source)
    return out


def weather_regions(session: Session) -> dict[str, list[str]]:
    """{crop: [regions]} — the regional weather targets a build holds: every held region the crop map gives area."""
    out = {}
    for c in registry():
        if not c.get("crop_map"):
            continue
        rw = W.regional_weights(c["commodity"])
        regs = sorted(r for r in held_regions(session, c["commodity"]) if r in rw)
        if regs:
            out[c["commodity"]] = regs
    return out


def _active(session: Session) -> dict[tuple[str, str], dict]:
    return {(r["commodity"], r["yield_region"]): dict(r) for r in session.execute(text("""
        SELECT spec_id::text, commodity, origin, yield_region, driver, yield_source, weather_kind, weather_key,
               season_months, season_prev_months, spei_scale, allow_cycle,
               EXISTS (SELECT 1 FROM crop_calibration_runs r WHERE r.spec_id = s.spec_id AND r.status = 'published')
                 AS published
        FROM crop_calibration_specs s WHERE retired_at IS NULL AND yield_region <> ''""")).mappings()}


def generate(session: Session) -> dict:
    """Create the missing regional recipes, retire the ones no longer generated and replace the regional coverage.
    Returns counts by status."""
    reg, gen = rule(), protocol()["generated"]
    m49 = _m49(session)
    active = _active(session)
    rows, created, retired, stale = [], 0, 0, []
    for c in registry():
        name = c["commodity"]
        if not c.get("crop_map"):
            continue
        rw, cw = W.regional_weights(name), W.weights(name)
        for region, (country, src) in sorted(held_regions(session, name).items()):
            area = float(rw[region][1].sum()) if region in rw else 0.0
            c_area = float(cw[country][1].sum()) if country in cw else 0.0
            share = area / c_area if c_area else 0.0
            row = {"c": name, "o": country, "g": region, "a": area, "sh": min(share, 1.0), "spec": None}
            held, want, se = None, None, None
            years = [y for y in yield_series.series(session, name, country, src, region) if y >= ERA5_FIRST]
            if share < min_share():
                held = ("small_area", f"{area:,.0f} ha of the crop grow here — {100 * share:.2f}% of the country's "
                                      f"{c_area:,.0f} ha, under the {100 * min_share():.0f}% a region needs")
            elif len(years) < min_years():
                held = ("too_few_years", f"{len(years)} years of regional yields since {ERA5_FIRST} — the test needs "
                                         f"at least {min_years()}")
            else:
                se = seasons.region_season(name, region, country, m49.get(country), area, c_area)
                if "held" in se:
                    held = ("no_season", se["held"])
                else:
                    want = {"yield_source": src, "driver": gen["driver"], "weather_key": crop_area.map_key(name),
                            "season_months": se["months"], "season_prev_months": se["prev_months"],
                            "spei_scale": gen["spei_scale"], "allow_cycle": is_alternate_bearing(name)}
            have = active.pop((name, region), None)
            if have:
                diff = _differs(have, want) if want else None
                if want and not diff:
                    rows.append({**row, "st": "recipe", "r": None, "spec": have["spec_id"]})
                    continue
                why = held[1] if held else "the recipe generated today differs: " + "; ".join(diff)
                if have["published"]:
                    stale.append({"commodity": name, "region": region, "spec_id": have["spec_id"], "reason": why})
                    rows.append({**row, "st": "recipe", "r": None, "spec": have["spec_id"]})
                    continue
                retire(session, have["spec_id"], why)
                retired += 1
            if held:
                rows.append({**row, "st": held[0], "r": held[1]})
                continue
            sid = specs.create(session, commodity=name, origin=country, yield_region=region, weather_kind="crop_area",
                               **want, basis=(f"generated by {reg['protocol']}: season {se['basis']}; weather over the "
                                              f"crop's area inside {region} ({crop_area.map_key(name)}); yield {src} "
                                              f"region {region}"),
                               protocol=reg["protocol"])
            created += 1
            rows.append({**row, "st": "recipe", "r": None, "spec": sid})
    for have in active.values():                 # a slot that is gone (its series or border no longer held)
        if have["published"]:
            stale.append({"commodity": have["commodity"], "region": have["yield_region"], "spec_id": have["spec_id"],
                          "reason": "the region no longer holds its declared regional series"})
        else:
            retire(session, have["spec_id"], "the region no longer holds its declared regional series")
            retired += 1
    session.execute(text("DELETE FROM crop_calibration_coverage WHERE region <> ''"))
    if rows:
        session.execute(text("""
            INSERT INTO crop_calibration_coverage (commodity, origin, region, area_ha, area_share, status, reason, spec_id)
            VALUES (:c, :o, :g, :a, :sh, :st, :r, CAST(:spec AS uuid))"""), rows)
    counts: dict[str, int] = {}
    for r in rows:
        counts[r["st"]] = counts.get(r["st"], 0) + 1
    return {"created": created, "retired": retired, "stale_published": stale, "coverage": counts}
